import os
import subprocess


def get_sensor_test_output() -> str:
    """Run pytest on sensor test suite and return summary lines."""
    cmd = [
        sys.executable,
        "-m", "pytest",
        "tests/xvs/test_sensor_srgb.py",
        "tests/xvs/test_sensor_psf.py",
        "tests/xvs/test_sensor_distortion.py",
        "tests/xvs/test_sensor_vignetting.py",
        "tests/xvs/test_sensor_emva1288.py",
        "tests/xvs/test_sensor_chain.py",
        "-v",
    ]
    env = os.environ.copy()
    env["PYTHONPATH"] = "src"
    proc = subprocess.run(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        cwd=REPO_ROOT,
        env=env,
        timeout=180,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"Sensor tests failed:\n{proc.stdout}")

    lines = proc.stdout.strip().splitlines()
    summary_lines = []
    for line in lines:
        if "::" in line or "passed" in line or "test session starts" in line or "rootdir:" in line:
            summary_lines.append(line)
    return "\n".join(summary_lines) if summary_lines else proc.stdout.strip()


