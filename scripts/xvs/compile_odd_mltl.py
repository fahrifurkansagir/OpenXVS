"""Deterministic compiler from `configs/xvs/odd/v2_m1_odd.yaml` to `#![no_std]` Rust `odd_generated.rs`.

Zero third-party dependencies (pure Python stdlib) so `.venv` runs deterministically without PyYAML.
Embeds the exact SHA-256 digest of the YAML contract into `odd_generated.rs` for cryptographic traceability.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_ODD_YAML = REPO_ROOT / "configs" / "xvs" / "odd" / "v2_m1_odd.yaml"
DEFAULT_OUT_RS = REPO_ROOT / "xvs-core" / "crates" / "xvs-rta-core" / "src" / "odd_generated.rs"


def parse_simple_odd_yaml(text: str) -> dict[str, Any]:
    """Parse the flat + 1-level-nested YAML schema of `v2_m1_odd.yaml` deterministically."""
    root: dict[str, Any] = {}
    current_section: str | None = None

    for raw_line in text.splitlines():
        # Strip full-line comments and trailing inline comments outside quotes
        stripped = raw_line.strip()
        if not stripped or stripped.startswith("#"):
            continue

        indent = len(raw_line) - len(raw_line.lstrip(" "))
        # Remove inline comment if value is unquoted
        line_clean = raw_line.rstrip()
        if "#" in line_clean and '"' not in line_clean and "'" not in line_clean:
            line_clean = line_clean.split("#", 1)[0].rstrip()

        if ":" not in line_clean:
            raise ValueError(f"Invalid YAML line: {raw_line!r}")

        key_part, val_part = line_clean.split(":", 1)
        key = key_part.strip()
        val_str = val_part.strip()

        if indent == 0:
            if val_str == "":
                root[key] = {}
                current_section = key
            else:
                root[key] = _parse_scalar(val_str)
                current_section = None
        else:
            if current_section is None or not isinstance(root.get(current_section), dict):
                raise ValueError(f"Indented entry without parent section: {raw_line!r}")
            root[current_section][key] = _parse_scalar(val_str)

    return root


def _parse_scalar(val_str: str) -> Any:
    if (val_str.startswith('"') and val_str.endswith('"')) or (
        val_str.startswith("'") and val_str.endswith("'")
    ):
        return val_str[1:-1]
    try:
        return int(val_str)
    except ValueError:
        return val_str


def compile_odd_to_rust(yaml_path: Path = DEFAULT_ODD_YAML, out_path: Path = DEFAULT_OUT_RS) -> str:
    """Compile `v2_m1_odd.yaml` into `odd_generated.rs` and return the source YAML SHA-256."""
    raw_bytes = yaml_path.read_bytes()
    normalized_text = raw_bytes.decode("utf-8").replace("\r\n", "\n")
    yaml_sha256 = hashlib.sha256(normalized_text.encode("utf-8")).hexdigest()
    doc = parse_simple_odd_yaml(normalized_text)

    if doc["schema"] != "xvs.v2_m1_odd/1":
        raise ValueError(f"Unexpected ODD schema: {doc['schema']!r}")

    thr = doc["thresholds"]
    tick_rate_hz = int(doc["tick_rate_hz"])
    ring_cap = int(doc["ring_buffer_capacity"])
    if ring_cap != 64:
        raise ValueError(f"Expected ring_buffer_capacity == 64, got {ring_cap}")

    rust_src = f'''// @generated by scripts/xvs/compile_odd_mltl.py from configs/xvs/odd/v2_m1_odd.yaml.
// DO NOT EDIT BY HAND. Re-run scripts/xvs/compile_odd_mltl.py after modifying the ODD contract.

/// SHA-256 digest of normalized `configs/xvs/odd/v2_m1_odd.yaml` (LF line endings).
pub const ODD_YAML_SHA256: &str = "{yaml_sha256}";

/// RTA execution rate in Hz (10 Hz -> 1 tick = 0.10 s).
pub const RTA_TICK_RATE_HZ: u32 = {tick_rate_hz};

/// Fixed ring-buffer capacity in ticks (power of 2 for mask indexing, zero heap).
pub const MLTL_RING_CAPACITY: usize = {ring_cap};

/// Single-camera epipolar residual upper threshold in SI microradians (`~0.35 deg`).
pub const EPIPOLAR_CAM_MAX_URAD: i64 = {int(thr["epipolar_cam_max_urad"])};

/// Default horizon attitude alert limit in SI microradians (`0.50 deg`).
pub const HORIZON_AL_URAD: i64 = {int(thr["horizon_al_urad"])};

/// Cat I vertical alert limit in SI millimetres (`10.0 m`).
pub const V_VAL_MM: i64 = {int(thr["v_val_mm"])};

/// Cat I horizontal alert limit in SI millimetres (`40.0 m`).
pub const V_HAL_MM: i64 = {int(thr["v_hal_mm"])};

/// Hard consecutive transient-dropout cap in `P2 (DegradedCoast)` (`1.0 s`).
pub const CONSEC_DROPOUT_MAX_TICKS: u32 = {int(thr["consec_dropout_max_ticks"])};

/// Sliding window length for intermittent dropout duty-cycle rule `R_DROPOUT_DUTY_20` (`2.0 s`).
pub const WINDOW_DROPOUT_LEN_TICKS: usize = {int(thr["window_dropout_len_ticks"])};

/// Maximum tolerated dropout ticks within `WINDOW_DROPOUT_LEN_TICKS` (`<= 50%` vs `>= 55%` -> `P0`).
pub const WINDOW_DROPOUT_20_MAX_TICKS: u8 = {int(thr["window_dropout_20_max_ticks"])};

/// Consecutive healthy ticks required for staged upward exit `P0 -> P1` (`3.0 s`).
pub const P0_RECOVERY_TICKS: u32 = {int(thr["p0_recovery_ticks"])};

/// Consecutive dwell ticks required for staged upward climb `P1 -> P3/P4` and `P3 -> P4` (`2.0 s`).
pub const DWELL_TICKS: u32 = {int(thr["dwell_ticks"])};

/// Minimum healthy cameras required for non-inhibited operation (`6 -> 5 -> 4`; `< 4` -> `P0`).
pub const MIN_HEALTHY_CAMS: u8 = {int(thr["min_healthy_cams"])};

/// Past-time `H[0, n]` window for `R_CAM_COUNT` (`H[0, 2](active_healthy_cams >= 4)`).
pub const CAM_COUNT_HISTORY_WINDOW: usize = {int(thr["cam_count_history_window"])};

/// Past-time `O[0, n]` window for `R_EPI_SINGLE_CAM[i]` (`O[0, 1](epipolar_max_urad[i] > 6109)`).
pub const EPI_ONCE_WINDOW: usize = {int(thr["epi_once_window"])};

/// Past-time `O[0, n]` window for `R_SPOOF_LOCK` (`O[0, 0](spoof_alarm)`).
pub const SPOOF_ONCE_WINDOW: usize = {int(thr["spoof_once_window"])};
'''
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(rust_src, encoding="utf-8", newline="\n")
    return yaml_sha256


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compile OpenXVS V2 M1 ODD YAML into odd_generated.rs.")
    parser.add_argument("--odd-yaml", type=Path, default=DEFAULT_ODD_YAML)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT_RS)
    args = parser.parse_args(argv)
    sha = compile_odd_to_rust(yaml_path=args.odd_yaml, out_path=args.out)
    print(f"Compiled {args.odd_yaml} (sha256={sha}) -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
